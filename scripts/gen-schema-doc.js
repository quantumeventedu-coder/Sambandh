#!/usr/bin/env node
// scripts/gen-schema-doc.js — generate ONE canonical, always-current schema document from the real
// models + the DB-hardening spec. No hand-maintenance, no drift. Run: `npm run schema:doc`.
//
// It reads model definitions only (no DB connection needed), so it's safe to run anywhere.

process.env.DATABASE_URL = process.env.DATABASE_URL || 'postgresql://pglite/schemadoc';   // pick the pg engine (no connect)

const fs = require('fs');
const path = require('path');
const pgodm = require('../src/db/pg-odm');
const { RELATIONS } = require('../src/db/schema-hardening');

const modelsDir = path.join(__dirname, '..', 'src', 'models');
for (const f of fs.readdirSync(modelsDir)) if (f.endsWith('.js')) { try { require(path.join(modelsDir, f)); } catch { /* skip unloadable */ } }

const { registeredModels, tableName } = pgodm._schema;

const relByModel = Object.fromEntries(RELATIONS.map((r) => [r.model, r]));
const typeName = (t) => (typeof t === 'function' ? t.name : (t === pgodm.Types.ObjectId ? 'ObjectId' : (t === pgodm.Types.Mixed ? 'Mixed' : String(t || 'Mixed'))));

/** @param {any} raw */
function describeField(raw) {
  if (typeof raw === 'function') return { type: typeName(raw) };
  if (Array.isArray(raw)) return { type: 'Array' };
  if (raw && typeof raw === 'object') {
    if (raw.type) return { type: typeName(raw.type), required: !!raw.required, enum: raw.enum, ref: raw.ref, unique: !!raw.unique, index: !!raw.index, min: raw.min, max: raw.max };
    return { type: 'Object' };   // nested subdocument
  }
  return { type: 'Mixed' };
}

let out = `# Canonical Data Model (generated)

> Generated by \`scripts/gen-schema-doc.js\` from the real models + \`src/db/schema-hardening.js\`.
> Do not edit by hand — run \`npm run schema:doc\` to refresh. Storage is Postgres via pg-odm:
> every model is one table \`(id text primary key, doc jsonb)\`. The **DB-enforced** column lists the
> constraints Postgres physically guarantees (enum whitelists, numeric ranges, foreign keys) so
> invalid or orphaned rows cannot be written regardless of application code.

`;

const names = Object.keys(registeredModels).sort();
out += `**${names.length} models.** Foreign keys ride STORED generated columns derived from the JSONB; ` +
  `user-referencing FKs on retained financial records are intentionally omitted (DPDP erasure hard-deletes users).\n\n`;

for (const name of names) {
  const M = registeredModels[name];
  const def = (M.schema && M.schema.def) || {};
  const rel = relByModel[name] || {};
  const fkFields = new Set((rel.fk || []).map((/** @type {any} */ x) => x.field));
  out += `## \`${tableName(name)}\`  (model \`${name}\`)\n\n`;
  out += `| field | type | required | enum / ref | DB-enforced |\n|---|---|---|---|---|\n`;
  for (const [field, raw] of Object.entries(def)) {
    const d = describeField(raw);
    const notes = [];
    if (d.enum) notes.push('enum ✓');
    if (typeof d.min === 'number' || typeof d.max === 'number') notes.push(`range ${d.min ?? '-∞'}..${d.max ?? '∞'} ✓`);
    if (fkFields.has(field)) notes.push('FK ✓');
    if (d.unique) notes.push('unique ✓');
    const enumRef = d.enum ? `enum(${d.enum.slice(0, 6).join(', ')}${d.enum.length > 6 ? ', …' : ''})` : (d.ref ? `→ ${d.ref}` : '');
    out += `| ${field} | ${d.type} | ${d.required ? 'yes' : ''} | ${enumRef} | ${notes.join(', ')} |\n`;
  }
  for (const chk of (rel.checks || [])) out += `| _(check)_ | | | | \`${chk.name}\`: ${chk.sql} |\n`;
  out += `\n`;
}

const dest = path.join(__dirname, '..', 'docs', 'schema.md');
fs.writeFileSync(dest, out);
console.log(`[OK] wrote ${dest} (${names.length} models)`);
